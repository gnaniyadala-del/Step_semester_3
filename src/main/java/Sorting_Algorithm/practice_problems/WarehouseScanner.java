package main.java.Sorting_Algorithm.assignment_problems;

public class WarehouseScanner {
    public record Summary(int total, int maxRow, int maxCol) {}

    public static Summary warehouseSummary(int[][] grid) {
        if (grid == null || grid.length == 0 || grid[0].length == 0) {
            return new Summary(0, -1, -1);
        }

        int total = 0;
        int maxVal = -1;
        int maxRow = 0;
        int maxCol = 0;

        for (int r = 0; r < grid.length; r++) {
            for (int c = 0; c < grid[0].length; c++) {
                int val = grid[r][c];
                total += val;
                if (val > maxVal) {
                    maxVal = val;
                    maxRow = r;
                    maxCol = c;
                }
            }
        }
        return new Summary(total, maxRow, maxCol);
    }

    public static void main(String[] args) {
        int[][] grid = {
                {4, 9, 2},
                {7, 1, 6},
                {3, 12, 5}
        };

        Summary res = warehouseSummary(grid);
        System.out.println("total = " + res.total() + ", maxCoordinate = (" + res.maxRow() + ", " + res.maxCol() + ")");
    }
}
